begin;
create table public.visitantes (
 visitante_id uuid primary key default gen_random_uuid(),
 nome text not null check(length(btrim(nome)) between 1 and 200),
 telefone text not null check(telefone ~ '^[0-9]{8,15}$'),
 status text not null default 'novo',
 criado_em timestamptz not null default now(),
 primeira_visita timestamptz not null default now(),
 ultima_visita timestamptz not null default now(),
 total_visitas integer not null default 1 check(total_visitas>=0),
 total_conversoes integer not null default 0 check(total_conversoes>=0),
 primeira_utm_source text,
 ultima_utm_source text
);
create index visitantes_telefone_idx on public.visitantes(telefone);
create index visitantes_ultima_visita_idx on public.visitantes(ultima_visita desc);
create table public.agendamentos (
 id bigint generated by default as identity primary key,
 visitante_id uuid not null references public.visitantes(visitante_id) on delete restrict,
 data_avaliacao timestamptz not null,
 status text not null default 'agendado' check(status in ('agendado','cancelado','realizado')),
 observacao text,
 criado_em timestamptz not null default now(),
 lembrete_enviado_em timestamptz,
 confirmado_em timestamptz
);
create index agendamentos_paciente_criado_idx on public.agendamentos(visitante_id,criado_em desc);
create index agendamentos_data_idx on public.agendamentos(data_avaliacao) where status<>'cancelado';
create unique index agendamentos_horario_ativo_idx on public.agendamentos(data_avaliacao) where status='agendado';
create table public.conversoes (
 id bigint generated by default as identity primary key,
 visitante_id uuid not null references public.visitantes(visitante_id) on delete restrict,
 tipo text not null default 'manual' check(tipo='manual'),
 valor numeric(12,2) not null check(valor>0),
 observacao text,
 status text not null default 'confirmado',
 origem text not null default 'manual',
 criado_em timestamptz not null default now(),
 valor_atualizado_em timestamptz not null default now()
);
create index conversoes_paciente_criado_idx on public.conversoes(visitante_id,criado_em desc);
create index conversoes_valor_data_idx on public.conversoes(valor_atualizado_em);
create table public.lancamentos_financeiros (
 id bigint generated by default as identity primary key,
 visitante_id uuid not null references public.visitantes(visitante_id) on delete restrict,
 tipo text not null check(tipo in ('atendimento','reembolso')),
 descricao text not null check(length(btrim(descricao)) between 1 and 250),
 valor numeric(12,2) not null check(valor>0 and valor<=1000000),
 forma_pagamento text check(forma_pagamento in ('pix','dinheiro','debito','credito')),
 parcelas integer not null default 1 check(parcelas between 1 and 12),
 reembolso_de_id bigint references public.lancamentos_financeiros(id) on delete restrict,
 observacao text,
 registrado_por_id uuid references auth.users(id) on delete set null,
 registrado_por_email text,
 registrado_por_nome text,
 criado_em timestamptz not null default now(),
 check((tipo='reembolso' and reembolso_de_id is not null) or (tipo='atendimento' and reembolso_de_id is null)),
 check(tipo='reembolso' or forma_pagamento is not null)
);
create index lancamentos_paciente_criado_idx on public.lancamentos_financeiros(visitante_id,criado_em desc);
create index lancamentos_data_idx on public.lancamentos_financeiros(criado_em);
create index lancamentos_reembolso_idx on public.lancamentos_financeiros(reembolso_de_id);
create index lancamentos_responsavel_idx on public.lancamentos_financeiros(registrado_por_id);
alter table public.visitantes enable row level security;
alter table public.agendamentos enable row level security;
alter table public.conversoes enable row level security;
alter table public.lancamentos_financeiros enable row level security;
revoke all on public.visitantes,public.agendamentos,public.conversoes,public.lancamentos_financeiros from anon,authenticated;
grant select,insert,update,delete on public.visitantes,public.agendamentos,public.conversoes,public.lancamentos_financeiros to service_role;
revoke all on sequence public.agendamentos_id_seq,public.conversoes_id_seq,public.lancamentos_financeiros_id_seq from anon,authenticated;
grant usage,select on sequence public.agendamentos_id_seq,public.conversoes_id_seq,public.lancamentos_financeiros_id_seq to service_role;
comment on table public.visitantes is 'Cadastro interno da Kahenna. Acesso somente pelo servidor autenticado, sem rastreamento de campanhas.';
comment on table public.agendamentos is 'Agenda e confirmações manuais da Kahenna.';
comment on table public.conversoes is 'Compatibilidade para registros financeiros manuais; sem integração com Meta.';
comment on table public.lancamentos_financeiros is 'Recebimentos e reembolsos com identificação do responsável.';
notify pgrst,'reload schema';
commit;
